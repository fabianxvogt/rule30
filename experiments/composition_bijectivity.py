#!/usr/bin/env python3
"""
Test: are compositions of MORE than h maps also bijections?
And what about the image size of k-step compositions for k < h?

Also: what's the GROUP generated by f_0, f_1 (as maps on {0,1}^h)?
Since individual maps are not bijections, they don't generate a group.
But the compositions of h-or-more maps might all be bijections.
"""
from __future__ import annotations
import os, sys, random
sys.path.insert(0, os.path.dirname(__file__))
from fast_class_coverage2 import rule30_next_tuple


def compose_maps(h, boundary_bits, start=None):
    """Apply sequence of f_{b} maps starting from each state in {0,1}^h.
    Returns the set of images."""
    all_states = range(1 << h)
    images = set()
    
    for s_int in all_states:
        state = tuple((s_int >> i) & 1 for i in range(h))
        if start is not None:
            state = start
        for b in boundary_bits:
            state = rule30_next_tuple(state, b)[:h]
        if start is not None:
            return state
        images.add(state)
    return images


def main():
    random.seed(42)
    
    for h in [5, 8, 10]:
        print(f"\n=== h={h} ===")
        N = 1 << h
        
        # Image size of k-step compositions for various k
        print(f"  Image size of random k-step compositions:")
        for k in range(1, 3*h+1):
            # Sample 10 random boundary sequences of length k
            sizes = []
            for _ in range(10):
                bits = [random.randint(0, 1) for _ in range(k)]
                images = compose_maps(h, bits)
                sizes.append(len(images))
            avg = sum(sizes) / len(sizes)
            mn, mx = min(sizes), max(sizes)
            is_bij = all(s == N for s in sizes)
            status = "BIJ" if is_bij else f"min={mn} max={mx} avg={avg:.0f}"
            if k <= h + 5 or k % h == 0 or is_bij:
                print(f"    k={k:3d}: {status}")
        
        # Test: are ALL compositions of length >= h bijections?
        print(f"\n  Testing bijection property for k=h..2h:")
        all_bij = True
        for k in range(h, 2*h+1):
            bij_count = 0
            total = 100
            for _ in range(total):
                bits = [random.randint(0, 1) for _ in range(k)]
                images = compose_maps(h, bits)
                if len(images) == N:
                    bij_count += 1
            if bij_count < total:
                all_bij = False
                print(f"    k={k}: {bij_count}/{total} bijections")
            else:
                print(f"    k={k}: all 100 bijections ✓")
        
        if all_bij:
            print(f"  ALL compositions of length >= h appear to be bijections!")


if __name__ == "__main__":
    main()
